using Microsoft.Data.Sqlite;
using Stenwatch.Core;
using Xunit;

namespace Stenwatch.Tests;

/// <summary>Defender TVM export -> fix actions: reading the export in all three shapes it turns up in, the ladder, the analyst's flags and the daily difference.</summary>
public class DefenderTriageTests
{
    const string Head = "Name,Severity,CVSS v3,Epss score,Age (days),Published,First detected,Updated,Has Exploit,Has Known Threats,Has Associated Alerts,Related Software,Exposed Machines,Description,Status";
    // Edge row: description has a comma inside quotes and a doubled quote. Firefox row: lists Thunderbird too, EPSS blank. KEV row: Unknown severity, no description.
    static readonly string[] Records =
    {
        "CVE-2026-1001,High,8.8,0.00300,30,\"27 May, 2026\",\"29 May, 2026\",\"06 Oct, 2026\",False,False,False,microsoft:edge_chromium-based,google:chrome,debian:chromium,150,\"Summary: Use after free, \"\"bad\"\". Fixed prior to 148.0.7778.216 on Mac. Generated by AI\",RemediationRequired",
        "CVE-2026-1002,Medium,6.5,,10,\"19 May, 2026\",\"19 May, 2026\",\"29 Aug, 2026\",False,False,False,oracle:firefox,mozilla:firefox,mozilla:thunderbird,40,\"Summary: fixed in Firefox 151 and Firefox ESR 140.11. Generated by AI\",RemediationRequired",
        "CVE-2026-1003,Unknown,0.0,,2,\"05 Oct, 2026\",\"05 Oct, 2026\",\"05 Oct, 2026\",False,False,False,microsoft:edge_chromium-based,1267,\"Summary: No vulnerability descriptions provided. Generated by AI\",RemediationRequired",
    };

    /// <summary>Same three records as (a) real CSV, (b) an xlsx with proper columns, (c) the CSV opened in Excel and split on commas (one record over many cells).</summary>
    static string[] Shapes(string dir)
    {
        var csv = Path.Combine(dir, "a.csv");
        File.WriteAllText(csv, "Vulnerabilities Export,07 Oct 2026\n" + Head + "\n" + string.Join("\n", Records));
        var columnar = Path.Combine(dir, "b.xlsx");
        DefenderTriage.WriteWorkbook(columnar, new[] { ("in", new[] { new[] { "Vulnerabilities Export" }, Head.Split(',') }
            .Concat(Csv.Parse(string.Join("\n", Records)).Select(r => new[] { r[0], r[1], r[2], r[3], r[4], r[5], r[6], r[7], r[8], r[9], r[10], string.Join(",", r.Skip(11).Take(r.Count - 14)), r[^3], r[^2], r[^1] })).ToList()) });
        var split = Path.Combine(dir, "c.xlsx");
        DefenderTriage.WriteWorkbook(split, new[] { ("in", new[] { new[] { "Vulnerabilities Export,07 Oct 2026" }, new[] { Head } }
            .Concat(Records.Select(Mangle)).ToList()) });
        return new[] { csv, columnar, split };
    }

    /// <summary>What the real file looks like: the first cell holds the record up to its first software, every later comma starts a new cell.</summary>
    static string[] Mangle(string rec)
    {
        var i = rec.IndexOf("False,False,False,") + "False,False,False,".Length; var j = rec.IndexOf(',', i);
        return new[] { rec[..j] }.Concat(rec[(j + 1)..].Split(',')).ToArray();
    }

    [Fact]
    public void Load_ReadsCsv_ProperXlsx_AndCommaSplitXlsx_ToTheSameRows()
    {
        var dir = Directory.CreateTempSubdirectory().FullName;
        var all = Shapes(dir).Select(DefenderTriage.Load).ToList();
        for (var shape = 0; shape < all.Count; shape++)
        {
            var rows = all[shape];
            Assert.True(rows.Count == 3, $"shape {shape} (0 csv, 1 columnar xlsx, 2 comma-split xlsx) parsed {rows.Count} of 3 records");
            Assert.Equal(new[] { "CVE-2026-1001", "CVE-2026-1002", "CVE-2026-1003" }, rows.Select(r => r.Cve));
            Assert.Equal(new[] { "Microsoft Edge", "Google Chrome" }, rows[0].Products);
            Assert.Equal(new[] { "Mozilla Firefox", "Mozilla Thunderbird" }, rows[1].Products);
            Assert.Equal(new[] { 150, 40, 1267 }, rows.Select(r => r.Exposed));
            Assert.Equal(0.003, rows[0].Epss);
            Assert.Contains("\"bad\"", rows[0].Description);
        }
    }

    [Fact]
    public void FixVersion_TakesTheHighestVersionNamed() =>
        Assert.Equal("151", DefenderTriage.FixVersion(new[] { "fixed in Firefox 151 and Firefox ESR 140.11", "prior to 9.1" }));

    [Fact]
    public void Rank_KevBeatsSeverity_EvenWhenNvdLacksTheCve_AndOneCveCanNeedTwoProducts()
    {
        var dir = Directory.CreateTempSubdirectory().FullName; var db = Path.Combine(dir, "cve.db");
        using (var c = new SqliteConnection($"Data Source={db}"))
        {
            c.Open(); using var cmd = c.CreateCommand();
            cmd.CommandText = "CREATE TABLE cve (id TEXT); CREATE TABLE epss (id TEXT, epss REAL); CREATE TABLE kev (id TEXT);" +
                "INSERT INTO cve VALUES ('CVE-2026-1001'); INSERT INTO kev VALUES ('CVE-2026-1003'); INSERT INTO epss VALUES ('CVE-2026-1002', 0.2)";
            cmd.ExecuteNonQuery();
        }
        var actions = DefenderTriage.Rank(DefenderTriage.Load(Shapes(dir)[0]), db);
        Assert.Equal("Act", actions.Single(a => a.Product == "Microsoft Edge").Tier);      // 1003 is KEV, though not in cve table and "Unknown" in Defender
        Assert.Equal("Attend", actions.Single(a => a.Product == "Mozilla Thunderbird").Tier); // EPSS 20% from cve.db
        Assert.Equal("151", actions.Single(a => a.Product == "Mozilla Firefox").Fix);
        Assert.Equal(3, DefenderTriage.CveCount(actions));
        Assert.Equal("Act", actions[0].Tier);
        Assert.All(actions, a => Assert.InRange(a.Label.Length, 1, 32)); // the grid shows Label; the full Rule is one click away
    }

    [Fact]
    public void Rank_WithoutCveDb_UsesDefenderDataAlone()
    {
        var a = DefenderTriage.Rank(DefenderTriage.Load(Shapes(Directory.CreateTempSubdirectory().FullName)[0]), null);
        Assert.Equal("Attend", a.Single(x => x.Product == "Google Chrome").Tier); // high severity, internet-facing browser, 150 machines (wide = 100+)
    }

    [Fact]
    public void Flags_RaiseLowerSnooze_AreKeptShownAndExpire()
    {
        var dir = Directory.CreateTempSubdirectory().FullName;
        var actions = DefenderTriage.Rank(DefenderTriage.Load(Shapes(dir)[0]), null);
        var edge = actions.Single(a => a.Product == "Microsoft Edge").Tier;
        DefenderTriage.SetFlag(dir, "Microsoft Edge", "Lower", "Intune ring 1 patches it");
        DefenderTriage.SetFlag(dir, "Mozilla Firefox", "Snooze", "waiting for ESR", "2026-11-01");
        var today = new DateOnly(2026, 10, 29);
        var flagged = DefenderTriage.ApplyFlags(actions, DefenderTriage.LoadFlags(dir), today);
        var e = flagged.Single(a => a.Product == "Microsoft Edge");
        Assert.Equal(DefenderTriage.Tiers[Array.IndexOf(DefenderTriage.Tiers, edge) + 1], e.Tier);
        Assert.Contains("Intune ring 1", e.Flag);
        Assert.True(flagged.Single(a => a.Product == "Mozilla Firefox").Snoozed);
        Assert.False(DefenderTriage.ApplyFlags(actions, DefenderTriage.LoadFlags(dir), new DateOnly(2026, 11, 2)).Single(a => a.Product == "Mozilla Firefox").Snoozed);
        Assert.Throws<ArgumentException>(() => DefenderTriage.SetFlag(dir, "x", "Maybe", ""));
    }

    [Fact]
    public void SaveAndCompare_ShowsNewGoneAndChanged_AndBriefingListsOnlyWhatChanged()
    {
        var dir = Directory.CreateTempSubdirectory().FullName;
        var rows = DefenderTriage.Load(Shapes(dir)[0]);
        var day1 = DefenderTriage.Rank(rows, null);
        Assert.False(DefenderTriage.SaveAndCompare(dir, day1, new DateOnly(2026, 10, 28)).HasPrevious);
        var day2 = DefenderTriage.Rank(rows.Where(r => r.Cve != "CVE-2026-1002").ToList(), null); // Firefox and Thunderbird gone
        var diff = DefenderTriage.SaveAndCompare(dir, day2, new DateOnly(2026, 10, 29));
        Assert.True(diff.HasPrevious);
        Assert.Equal(new[] { "Mozilla Firefox", "Mozilla Thunderbird" }, diff.Gone.Order());
        var html = DefenderTriage.Html(day2, diff, "x.xlsx", new DateOnly(2026, 10, 29));
        Assert.Contains("Since 2026-10-28", html);
        Assert.Contains("not validated", html);
    }

    [Fact]
    public void WriteXlsx_CanBeReadBack()
    {
        var dir = Directory.CreateTempSubdirectory().FullName; var path = Path.Combine(dir, "o.xlsx");
        var actions = DefenderTriage.Rank(DefenderTriage.Load(Shapes(dir)[0]), null);
        DefenderTriage.WriteXlsx(path, actions);
        var cells = Inventory.XlsxCells(path);
        Assert.Equal("Tier", cells[0][0]);
        Assert.Equal(actions.Count + 1, cells.Count);
    }
}
